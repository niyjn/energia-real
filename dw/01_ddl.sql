/* =====================================================================
   DATA WAREHOUSE CAMPO REAL ENERGIA - DDL (PostgreSQL 13+)
   ---------------------------------------------------------------------
   Star schema no schema dw. Lê apenas das camadas tratadas:
     stg.*      (origem limpa pela etapa de qualidade)
     tratada.*  (PLD da CCEE e clima da Open-Meteo)
     qualidade.* (métricas, para o painel de confiança)

   Idempotente: CREATE ... IF NOT EXISTS. Para recriar do zero:
       python dw/carregar_dw.py --recriar

   GRÃOS (declarados antes das tabelas):
     fato_geracao       1 linha = 1 usina x 1 hora medida
     fato_pld           1 linha = 1 submercado x 1 hora
     fato_parada_hora   1 linha = 1 usina x 1 hora dentro de uma parada
     fato_qualidade     1 linha = 1 regra x 1 fase (origem/stg) x 1 execução
     fato_impacto       1 linha = 1 indicador x 1 recorte x 1 execução
   ===================================================================== */

CREATE SCHEMA IF NOT EXISTS dw;

-- ---------------------------------------------------------------- dimensões

-- Tempo no grão hora. sk_tempo = AAAAMMDDHH (legível e ordenável); -1 = desconhecido.
CREATE TABLE IF NOT EXISTS dw.dim_tempo (
    sk_tempo            INTEGER      PRIMARY KEY,
    data_hora           TIMESTAMP    UNIQUE,           -- início da hora, horário de Brasília
    data                DATE,
    ano                 SMALLINT,
    trimestre           SMALLINT,
    mes                 SMALLINT,
    nome_mes            VARCHAR(10),
    ano_mes             CHAR(7),                        -- '2025-01'
    dia                 SMALLINT,
    dia_semana          SMALLINT,                       -- 1 = segunda ... 7 = domingo (ISO)
    nome_dia_semana     VARCHAR(10),
    hora                SMALLINT,
    fim_de_semana       BOOLEAN,
    feriado             BOOLEAN,                        -- feriado nacional
    ponto_facultativo   BOOLEAN,                        -- Carnaval, Corpus Christi
    nome_feriado        VARCHAR(60),
    dia_util            BOOLEAN,                        -- não é fim de semana, feriado nem ponto facultativo
    estacao             VARCHAR(10),                    -- hemisfério sul
    periodo_hidrologico VARCHAR(5),                     -- Úmido (nov-abr) / Seco (mai-out)
    patamar_carga       VARCHAR(7),                     -- Leve / Média / Pesada (regra simplificada, ver docs)
    horario_ponta       BOOLEAN                         -- 18h-20h em dia útil
);

CREATE TABLE IF NOT EXISTS dw.dim_submercado (
    sk_submercado   INTEGER     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_submercado  VARCHAR(2)  NOT NULL UNIQUE,        -- VARCHAR: sem o espaço que o CHAR(2) deixava em 'N ' e 'S '
    nome            VARCHAR(40) NOT NULL,
    regioes         VARCHAR(80)
);

CREATE TABLE IF NOT EXISTS dw.dim_fonte (
    sk_fonte      INTEGER     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_fonte     VARCHAR(10) NOT NULL UNIQUE,
    descricao     VARCHAR(40) NOT NULL,
    renovavel     BOOLEAN,
    intermitente  BOOLEAN
);

-- Usina com SCD tipo 2 (nome, potência, situação, fonte, submercado) e tipo 1 (correções de cadastro).
CREATE TABLE IF NOT EXISTS dw.dim_usina (
    sk_usina              INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_usina             VARCHAR(12)  NOT NULL,       -- chave natural
    nome                  VARCHAR(80)  NOT NULL,
    cod_fonte             VARCHAR(10),
    cod_submercado        VARCHAR(2),
    uf                    CHAR(2),
    municipio             VARCHAR(60),
    latitude              NUMERIC(9,6),
    longitude             NUMERIC(9,6),
    potencia_mw           NUMERIC(8,2),
    data_inicio_operacao  DATE,
    situacao              VARCHAR(20),
    flag_qualidade        TEXT,
    hash_scd2             CHAR(32),                     -- md5 dos atributos tipo 2
    valido_de             TIMESTAMP    NOT NULL,
    valido_ate            TIMESTAMP    NOT NULL DEFAULT '9999-12-31',
    versao_atual          BOOLEAN      NOT NULL DEFAULT TRUE
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_dim_usina_versao_atual ON dw.dim_usina (cod_usina) WHERE versao_atual;

-- ---------------------------------------------------------------- fatos

CREATE TABLE IF NOT EXISTS dw.fato_pld (
    sk_tempo       INTEGER       NOT NULL REFERENCES dw.dim_tempo,
    sk_submercado  INTEGER       NOT NULL REFERENCES dw.dim_submercado,
    pld            NUMERIC(10,2) NOT NULL,              -- R$/MWh
    PRIMARY KEY (sk_tempo, sk_submercado)
);

-- Clima da Open-Meteo entra como atributo da geração: mesmo grão (usina x hora) e ponto 1:1 com a usina.
CREATE TABLE IF NOT EXISTS dw.fato_geracao (
    sk_tempo            INTEGER        NOT NULL REFERENCES dw.dim_tempo,
    sk_usina            INTEGER        NOT NULL REFERENCES dw.dim_usina,
    sk_fonte            INTEGER        NOT NULL REFERENCES dw.dim_fonte,
    sk_submercado       INTEGER        NOT NULL REFERENCES dw.dim_submercado,
    energia_mwh         NUMERIC(12,3),
    disponibilidade_mw  NUMERIC(8,2),
    potencia_mw         NUMERIC(8,2),                   -- potência da versão da usina na hora (para fator de capacidade)
    pld                 NUMERIC(10,2),                  -- PLD do submercado da usina na hora
    receita_pld         NUMERIC(16,2),                  -- energia_mwh x pld
    em_parada           BOOLEAN        NOT NULL DEFAULT FALSE,
    status_qualidade    VARCHAR(12)    NOT NULL,        -- ORIGINAL / CORRIGIDO / IMPUTADO / SINALIZADO
    radiacao_wm2        NUMERIC(7,2),
    vento_10m_ms        NUMERIC(5,2),
    vento_100m_ms       NUMERIC(5,2),
    temperatura_c       NUMERIC(5,2),
    precipitacao_mm     NUMERIC(6,2),
    nuvens_pct          NUMERIC(5,1),
    PRIMARY KEY (sk_tempo, sk_usina)
);
CREATE INDEX IF NOT EXISTS ix_fato_geracao_usina ON dw.fato_geracao (sk_usina);
CREATE INDEX IF NOT EXISTS ix_fato_geracao_fonte ON dw.fato_geracao (sk_fonte);

CREATE TABLE IF NOT EXISTS dw.fato_parada_hora (
    sk_tempo               INTEGER       NOT NULL REFERENCES dw.dim_tempo,
    sk_usina               INTEGER       NOT NULL REFERENCES dw.dim_usina,
    sk_fonte               INTEGER       NOT NULL REFERENCES dw.dim_fonte,
    sk_submercado          INTEGER       NOT NULL REFERENCES dw.dim_submercado,
    id_parada              INTEGER       NOT NULL,      -- dimensão degenerada
    tipo_parada            VARCHAR(20)   NOT NULL,      -- Programada / Forçada
    motivo                 VARCHAR(120),
    energia_esperada_mwh   NUMERIC(12,3),               -- NULL quando não há base de comparação
    pld                    NUMERIC(10,2),
    receita_perdida_rs     NUMERIC(16,2),
    metodo_estimativa      VARCHAR(60)   NOT NULL,
    PRIMARY KEY (sk_tempo, sk_usina, id_parada)
);

CREATE TABLE IF NOT EXISTS dw.fato_qualidade (
    id_execucao       BIGINT        NOT NULL,
    executado_em      TIMESTAMP     NOT NULL,
    fase              VARCHAR(10)   NOT NULL,           -- origem (antes da limpeza) / stg (depois)
    regra             VARCHAR(80)   NOT NULL,
    dimensao          VARCHAR(30)   NOT NULL,
    tabela            VARCHAR(40)   NOT NULL,
    descricao         TEXT,
    avaliados         INTEGER       NOT NULL,
    falhas            INTEGER       NOT NULL,
    pct_conformidade  NUMERIC(9,4),
    PRIMARY KEY (id_execucao, fase, regra)
);

CREATE TABLE IF NOT EXISTS dw.fato_impacto (
    id_execucao   BIGINT        NOT NULL,
    indicador     VARCHAR(40)   NOT NULL,
    recorte       VARCHAR(20)   NOT NULL,
    antes         NUMERIC(18,2),
    depois        NUMERIC(18,2),
    diferenca     NUMERIC(18,2),
    variacao_pct  NUMERIC(12,4),
    PRIMARY KEY (id_execucao, indicador, recorte)
);
