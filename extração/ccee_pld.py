"""Extrator do PLD horário da CCEE (API CKAN do portal de dados abertos).

Fluxo:
  1. descobre o resource_id de cada ano (ou usa o fixado no config.ini)
  2. baixa paginando com datastore_search e grava cada registro em raw.ccee_pld_raw (JSONB, sem alterar)
  3. trata o raw (tipos, submercado -> SE/S/NE/N, data+hora) e faz upsert em tratada.pld_horario

Grão da tabela tratada: 1 submercado x 1 hora (PK data_hora + cod_submercado).
Reexecutar é seguro: só baixa o que ainda não está no raw (use --refazer para baixar tudo de novo).

Uso:  python ccee_pld.py [--anos 2025 2026] [--refazer] [--so-tratar]
Fonte: CCEE, Dados Abertos, conjunto PLD_HORARIO, licença CC-BY 4.0.
"""
from __future__ import annotations

import argparse
import re
import sys
import unicodedata
from datetime import datetime
from decimal import Decimal, InvalidOperation

from psycopg import sql
from psycopg.types.json import Jsonb

import common
from common import ErroFonte, execucao, get_json, log, tabela

FONTE = "ccee_pld"

SUBMERCADOS = {
    "SUDESTE": "SE", "SUDESTE/CENTRO-OESTE": "SE", "SE/CO": "SE", "SECO": "SE", "SE": "SE",
    "SUL": "S", "S": "S",
    "NORDESTE": "NE", "NE": "NE",
    "NORTE": "N", "N": "N",
}

_DDL_RAW = """
CREATE TABLE IF NOT EXISTS {raw} (
    id_raw      BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource_id TEXT        NOT NULL,
    ckan_id     BIGINT      NOT NULL,          -- _id do registro no CKAN
    payload     JSONB       NOT NULL,          -- registro exatamente como chegou
    origem      TEXT        NOT NULL,          -- URL consultada
    extraido_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    id_execucao BIGINT,
    CONSTRAINT uk_ccee_pld_raw UNIQUE (resource_id, ckan_id)
)
"""

_DDL_TRATADA = """
CREATE TABLE IF NOT EXISTS {tratada} (
    data_hora      TIMESTAMP     NOT NULL,     -- início da hora, horário de Brasília
    cod_submercado CHAR(2)       NOT NULL,     -- SE, S, NE, N
    pld            NUMERIC(10,2) NOT NULL,     -- R$/MWh
    resource_id    TEXT          NOT NULL,
    extraido_em    TIMESTAMPTZ   NOT NULL,
    carregado_em   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT pk_pld_horario PRIMARY KEY (data_hora, cod_submercado)
)
"""


# --------------------------------------------------------------------------- #
# Descoberta dos recursos
# --------------------------------------------------------------------------- #
def descobrir_resources(cfg, sessao, anos: list[int]) -> dict[int, str]:
    fixos = {int(k): v.strip() for k, v in cfg["ccee_resource_ids"].items() if v.strip()} \
        if cfg.has_section("ccee_resource_ids") else {}
    resources = {ano: fixos[ano] for ano in anos if ano in fixos}
    faltam = [a for a in anos if a not in resources]
    if not faltam:
        return resources

    pacote = get_json(sessao, f"{cfg['ccee']['api_url']}/package_show", {"id": cfg["ccee"]["dataset"]}, cfg)
    if not pacote.get("success"):
        raise ErroFonte(f"package_show sem sucesso: {str(pacote)[:200]}")
    candidatos = pacote["result"].get("resources", [])
    for ano in faltam:
        achados = [r for r in candidatos
                   if re.search(rf"(?<!\d){ano}(?!\d)", f"{r.get('name', '')} {r.get('url', '')}")]
        achados.sort(key=lambda r: not r.get("datastore_active", False))  # prefere os consultáveis por API
        if not achados:
            log.warning("nenhum recurso de %s no dataset %s (ainda não publicado?)", ano, cfg["ccee"]["dataset"])
            continue
        resources[ano] = achados[0]["id"]
        log.info("ano %s -> resource_id %s (%s)", ano, achados[0]["id"], achados[0].get("name"))
    return resources


# --------------------------------------------------------------------------- #
# Extração (raw)
# --------------------------------------------------------------------------- #
def _checar_colunas(cfg, campos: set[str]) -> None:
    """Detecta mudança de layout: cada coluna obrigatória precisa de ao menos um nome conhecido."""
    for logica in ("data", "submercado", "pld"):
        aliases = common.lista(cfg, "ccee_colunas", logica)
        if not any(a.upper() in campos for a in aliases):
            raise ErroFonte(f"mudança de colunas: nenhuma de {aliases} para '{logica}'. "
                            f"Colunas recebidas: {sorted(campos)}. Ajuste [ccee_colunas] no config.ini.")


def extrair_recurso(cfg, conn, sessao, ex, ano: int, resource_id: str, refazer: bool) -> None:
    raw = tabela(cfg, "raw", "ccee_pld_raw")
    url = f"{cfg['ccee']['api_url']}/datastore_search"
    limite = cfg["ccee"].getint("page_size", 5000)

    if refazer:
        conn.execute(sql.SQL("DELETE FROM {} WHERE resource_id = %s").format(raw), (resource_id,))
        conn.commit()
    # retoma de onde parou: registros já gravados não são baixados de novo
    offset = conn.execute(sql.SQL("SELECT count(*) FROM {} WHERE resource_id = %s").format(raw),
                          (resource_id,)).fetchone()[0]
    if offset:
        log.info("%s: %s registros já no raw; retomando do offset %s", ano, offset, offset)

    primeira = True
    while True:
        dados = get_json(sessao, url, {"resource_id": resource_id, "limit": limite, "offset": offset,
                                       "sort": "_id asc"}, cfg)
        if not dados.get("success"):
            raise ErroFonte(f"datastore_search sem sucesso: {str(dados.get('error', dados))[:300]}")
        resultado = dados["result"]
        registros = resultado.get("records") or []
        total = resultado.get("total")

        if not registros:
            if primeira and offset == 0:
                raise ErroFonte(f"recurso {resource_id} ({ano}) devolveu 0 registros")
            break  # fim da paginação

        origem = f"{url}?resource_id={resource_id}&limit={limite}&offset={offset}"
        with conn.cursor() as cur:
            cur.executemany(
                sql.SQL("INSERT INTO {} (resource_id, ckan_id, payload, origem, id_execucao) "
                        "VALUES (%s, %s, %s, %s, %s) ON CONFLICT (resource_id, ckan_id) DO NOTHING").format(raw),
                [(resource_id, r["_id"], Jsonb(r), origem, ex.id) for r in registros],
            )
            ex.gravadas += cur.rowcount if cur.rowcount > 0 else 0
        conn.commit()  # cada página é confirmada: uma queda no meio não perde o que já veio
        ex.lidas += len(registros)
        offset += len(registros)
        log.info("%s: %s/%s registros", ano, offset, total if total is not None else "?")

        if primeira:
            _checar_colunas(cfg, {f["id"].upper() for f in resultado.get("fields", [])} or
                            {k.upper() for k in registros[0]})
            primeira = False
        if total is not None and offset >= total:
            break


# --------------------------------------------------------------------------- #
# Tratamento (raw -> tratada)
# --------------------------------------------------------------------------- #
def _valor(r: dict, aliases: list[str]):
    for a in aliases:
        v = r.get(a.upper())
        if v not in (None, ""):
            return v
    return None


def _sem_acento(txt) -> str:
    return unicodedata.normalize("NFKD", str(txt)).encode("ascii", "ignore").decode().strip().upper()


def parse_registro(rec: dict, cols: dict[str, list[str]]) -> tuple[datetime, str, Decimal]:
    """Converte um registro raw em (data_hora, cod_submercado, pld). Levanta ValueError se inválido."""
    r = {k.upper(): v for k, v in rec.items()}

    bruto = _valor(r, cols["data"])
    if bruto is None:
        raise ValueError("data ausente")
    bruto, hora_txt = str(bruto).strip(), None
    if m := re.match(r"^(\d{4})-(\d{2})-(\d{2})(?:[T ](\d{2}))?", bruto):
        ano, mes, dia, hora_txt = int(m[1]), int(m[2]), int(m[3]), m[4]
    elif m := re.match(r"^(\d{2})/(\d{2})/(\d{4})", bruto):
        dia, mes, ano = int(m[1]), int(m[2]), int(m[3])
    elif bruto.isdigit():  # só o número do dia: o mês vem de MES_REFERENCIA (AAAAMM)
        ref = re.match(r"^(\d{4})\D?(\d{2})$", str(_valor(r, cols["mes_ref"]) or "").strip())
        if not ref:
            raise ValueError(f"dia '{bruto}' sem mês de referência")
        ano, mes, dia = int(ref[1]), int(ref[2]), int(bruto)
    else:
        raise ValueError(f"data em formato desconhecido: {bruto!r}")

    hora_col = _valor(r, cols["hora"])
    try:
        hora = int(float(str(hora_col).replace(",", "."))) if hora_col is not None else int(hora_txt)
    except (TypeError, ValueError):
        raise ValueError("hora ausente ou inválida") from None
    if not 0 <= hora <= 23:
        raise ValueError(f"hora fora de 0-23: {hora}")

    sub = SUBMERCADOS.get(_sem_acento(_valor(r, cols["submercado"]) or ""))
    if sub is None:
        raise ValueError(f"submercado desconhecido: {_valor(r, cols['submercado'])!r}")

    try:
        pld = Decimal(str(_valor(r, cols["pld"])).replace(",", "."))
    except InvalidOperation:
        raise ValueError(f"PLD inválido: {_valor(r, cols['pld'])!r}") from None
    return datetime(ano, mes, dia, hora), sub, pld


def tratar(cfg, conn, ex, resource_ids: list[str]) -> None:
    raw, trat = tabela(cfg, "raw", "ccee_pld_raw"), tabela(cfg, "tratada", "pld_horario")
    cols = {k: common.lista(cfg, "ccee_colunas", k) for k in ("data", "hora", "submercado", "pld", "mes_ref")}

    linhas, invalidas = [], []
    for resource_id, payload, extraido_em in conn.execute(
        sql.SQL("SELECT resource_id, payload, extraido_em FROM {} WHERE resource_id = ANY(%s) ORDER BY id_raw").format(raw),
        (resource_ids,),
    ):
        ex.lidas += 1
        try:
            data_hora, sub, pld = parse_registro(payload, cols)
            linhas.append((data_hora, sub, pld, resource_id, extraido_em))
        except ValueError as e:
            invalidas.append(f"{payload.get('_id')}: {e}")

    with conn.cursor() as cur:
        cur.executemany(
            sql.SQL("INSERT INTO {} (data_hora, cod_submercado, pld, resource_id, extraido_em) VALUES (%s, %s, %s, %s, %s) "
                    "ON CONFLICT (data_hora, cod_submercado) DO UPDATE SET pld = EXCLUDED.pld, "
                    "resource_id = EXCLUDED.resource_id, extraido_em = EXCLUDED.extraido_em, carregado_em = now()").format(trat),
            linhas,
        )
    conn.commit()
    ex.gravadas = len(linhas)
    if invalidas:
        ex.avisos.append(f"{len(invalidas)} registros do raw não puderam ser tratados (ex.: {'; '.join(invalidas[:3])})")


# --------------------------------------------------------------------------- #
def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Extrai o PLD horário da CCEE para o PostgreSQL.")
    ap.add_argument("--anos", nargs="+", type=int, help="anos a extrair (padrão: [ccee] anos do config.ini)")
    ap.add_argument("--refazer", action="store_true", help="apaga o raw dos recursos e baixa tudo de novo")
    ap.add_argument("--so-tratar", action="store_true", help="não baixa; só reprocessa raw -> tratada")
    args = ap.parse_args(argv)

    common.configurar_log()
    common.carregar_env()
    cfg = common.carregar_config()
    anos = args.anos or [int(a) for a in common.lista(cfg, "ccee", "anos")]
    falhas = 0

    with common.conectar() as conn:
        common.garantir_estrutura(conn, cfg)
        conn.execute(sql.SQL(_DDL_RAW).format(raw=tabela(cfg, "raw", "ccee_pld_raw")))
        conn.execute(sql.SQL(_DDL_TRATADA).format(tratada=tabela(cfg, "tratada", "pld_horario")))
        conn.commit()

        sessao = common.nova_sessao(cfg)
        resources: dict[int, str] = {}
        if args.so_tratar:
            rows = conn.execute(sql.SQL("SELECT DISTINCT resource_id FROM {}").format(tabela(cfg, "raw", "ccee_pld_raw"))).fetchall()
            resources = {i: r[0] for i, r in enumerate(rows)}
        else:
            try:
                with execucao(cfg, FONTE, "descoberta de recursos") as ex:
                    resources = descobrir_resources(cfg, sessao, anos)
                    ex.lidas = ex.gravadas = len(resources)
                    ex.avisos += [f"ano {a} sem recurso publicado" for a in anos if a not in resources]
            except ErroFonte as e:
                log.error("%s", e)
                return 1

            for ano, resource_id in resources.items():
                try:
                    with execucao(cfg, FONTE, f"extracao {ano} ({resource_id})") as ex:
                        extrair_recurso(cfg, conn, sessao, ex, ano, resource_id, args.refazer)
                except ErroFonte as e:
                    conn.rollback()
                    falhas += 1
                    log.error("ano %s: %s", ano, e)

        if resources:
            try:
                with execucao(cfg, FONTE, "tratamento raw -> tratada") as ex:
                    tratar(cfg, conn, ex, list(resources.values()))
            except Exception as e:  # noqa: BLE001 - já registrado no log_extracao
                conn.rollback()
                falhas += 1
                log.error("tratamento: %s", e)
    return 1 if falhas else 0


if __name__ == "__main__":
    sys.exit(main())
