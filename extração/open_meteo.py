"""Extrator de clima horário (Open-Meteo, API histórica) nas coordenadas das usinas.

Fluxo, por usina:
  1. lê cod_usina/latitude/longitude do cadastro de origem (somente leitura)
  2. consulta a API no fuso America/Sao_Paulo e grava a resposta inteira em raw.open_meteo_raw (JSONB)
  3. converte para tratada.clima_horario (grão: 1 usina x 1 hora, PK cod_usina + data_hora)

Cada usina recebe os dados do ponto exato das suas coordenadas (relação 1:1 usina -> ponto de clima).
Reexecutar é seguro: só baixa a partir do último dia já gravado (menos [open_meteo] reprocessar_ultimos_dias).

Observação: na Open-Meteo, radiação e precipitação de cada hora são médias/somas da hora ANTERIOR ao carimbo;
considere isso ao cruzar com a geração (que está carimbada no início da hora).

Uso:  python open_meteo.py [--usinas CRE-UFV-004 ...] [--refazer]
Fonte: Open-Meteo.com (CC-BY 4.0, uso não comercial) - https://open-meteo.com
"""
from __future__ import annotations

import argparse
import sys
from datetime import date, datetime, timedelta

from psycopg import sql
from psycopg.types.json import Jsonb

import common
from common import ErroFonte, execucao, get_json, log, tabela

FONTE = "open_meteo"

# variável da API -> coluna da tabela tratada
VARIAVEIS = {
    "temperature_2m": "temperatura_c",
    "precipitation": "precipitacao_mm",
    "cloud_cover": "nuvens_pct",
    "shortwave_radiation": "radiacao_wm2",
    "wind_speed_10m": "vento_10m_ms",
    "wind_speed_100m": "vento_100m_ms",
}

_DDL_RAW = """
CREATE TABLE IF NOT EXISTS {raw} (
    id_raw      BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_usina   VARCHAR(12)   NOT NULL,
    latitude    NUMERIC(9,6)  NOT NULL,
    longitude   NUMERIC(9,6)  NOT NULL,
    data_inicio DATE          NOT NULL,
    data_fim    DATE          NOT NULL,
    payload     JSONB         NOT NULL,        -- resposta exatamente como chegou
    origem      TEXT          NOT NULL,        -- URL e parâmetros
    extraido_em TIMESTAMPTZ   NOT NULL DEFAULT now(),
    id_execucao BIGINT
)
"""

_DDL_TRATADA = """
CREATE TABLE IF NOT EXISTS {tratada} (
    cod_usina       VARCHAR(12)  NOT NULL,
    data_hora       TIMESTAMP    NOT NULL,     -- horário de Brasília
    temperatura_c   NUMERIC(5,2),
    precipitacao_mm NUMERIC(6,2),
    nuvens_pct      NUMERIC(5,1),
    radiacao_wm2    NUMERIC(7,2),
    vento_10m_ms    NUMERIC(5,2),
    vento_100m_ms   NUMERIC(5,2),
    extraido_em     TIMESTAMPTZ  NOT NULL,
    carregado_em    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_clima_horario PRIMARY KEY (cod_usina, data_hora)
)
"""


def listar_usinas(cfg, conn, filtro: list[str] | None) -> list[tuple[str, float, float]]:
    """Usinas do cadastro (uma por código válido) com o override de coordenadas do config.ini aplicado."""
    # o regex descarta o cadastro duplicado/mal digitado (ex.: CRE-EOL-07)
    rows = conn.execute(sql.SQL(
        "SELECT DISTINCT ON (cod_usina) cod_usina, latitude, longitude FROM {} "
        "WHERE cod_usina ~ '^CRE-[A-Z]{{3}}-[0-9]{{3}}$' ORDER BY cod_usina").format(tabela(cfg, "origem", "usina"))
    ).fetchall()
    override = {}
    if cfg.has_section("open_meteo_coord_override"):
        for cod, valor in cfg["open_meteo_coord_override"].items():
            lat, lon = (float(x) for x in valor.split(","))
            override[cod] = (lat, lon)
    usinas = []
    for cod, lat, lon in rows:
        lat, lon = override.get(cod, (float(lat), float(lon)))
        if not filtro or cod in filtro:
            usinas.append((cod, lat, lon))
    return usinas


def coordenada_valida(cfg, lat: float, lon: float) -> bool:
    o = cfg["open_meteo"]
    return o.getfloat("lat_min") <= lat <= o.getfloat("lat_max") and o.getfloat("lon_min") <= lon <= o.getfloat("lon_max")


def periodo(cfg, conn, cod: str, refazer: bool) -> tuple[date, date]:
    o = cfg["open_meteo"]
    inicio = date.fromisoformat(o["inicio"])
    fim = date.fromisoformat(o["fim"]) if o.get("fim", "").strip() else date.today() - timedelta(days=o.getint("atraso_dias", 5))
    if not refazer:
        ultimo = conn.execute(sql.SQL("SELECT max(data_fim) FROM {} WHERE cod_usina = %s").format(tabela(cfg, "raw", "open_meteo_raw")),
                              (cod,)).fetchone()[0]
        if ultimo:  # reprocessa os últimos dias: a fonte pode revisar os mais recentes
            inicio = max(inicio, ultimo - timedelta(days=o.getint("reprocessar_ultimos_dias", 7)))
    return inicio, fim


def extrair_usina(cfg, conn, sessao, ex, cod: str, lat: float, lon: float, refazer: bool) -> None:
    if not coordenada_valida(cfg, lat, lon):
        ex.avisos.append(f"coordenadas fora do Brasil ({lat}, {lon}); usina ignorada. "
                         f"Corrija em [open_meteo_coord_override] se for erro de cadastro")
        return
    inicio, fim = periodo(cfg, conn, cod, refazer)
    if inicio > fim:
        log.info("%s: nada novo para baixar (fim=%s)", cod, fim)
        return

    url = cfg["open_meteo"]["url"]
    params = {"latitude": lat, "longitude": lon, "start_date": inicio.isoformat(), "end_date": fim.isoformat(),
              "hourly": ",".join(VARIAVEIS), "timezone": cfg["open_meteo"]["timezone"], "wind_speed_unit": "ms"}
    dados = get_json(sessao, url, params, cfg)

    if dados.get("error"):
        raise ErroFonte(f"API recusou a consulta: {dados.get('reason')}")
    horario = dados.get("hourly") or {}
    tempos = horario.get("time") or []
    if not tempos:
        raise ErroFonte(f"resposta vazia para {cod} ({inicio} a {fim})")
    ausentes = [v for v in VARIAVEIS if v not in horario]
    if ausentes:
        raise ErroFonte(f"mudança de colunas: variáveis ausentes na resposta: {ausentes}")
    if any(len(horario[v]) != len(tempos) for v in VARIAVEIS):
        raise ErroFonte("resposta inconsistente: séries com tamanhos diferentes")

    # raw: resposta inteira, como chegou
    origem = f"{url}?" + "&".join(f"{k}={v}" for k, v in params.items())
    extraido_em = conn.execute(
        sql.SQL("INSERT INTO {} (cod_usina, latitude, longitude, data_inicio, data_fim, payload, origem, id_execucao) "
                "VALUES (%s, %s, %s, %s, %s, %s, %s, %s) RETURNING extraido_em").format(tabela(cfg, "raw", "open_meteo_raw")),
        (cod, lat, lon, inicio, fim, Jsonb(dados), origem, ex.id),
    ).fetchone()[0]
    conn.commit()
    ex.lidas += len(tempos)

    # tratada: uma linha por hora; valores nulos da fonte ficam NULL (a decisão de tratá-los é da etapa de qualidade)
    linhas = [
        (cod, datetime.fromisoformat(t), *(horario[v][i] for v in VARIAVEIS), extraido_em)
        for i, t in enumerate(tempos)
    ]
    colunas = sql.SQL(", ").join(sql.Identifier(c) for c in VARIAVEIS.values())
    atualiza = sql.SQL(", ").join(sql.SQL("{0} = EXCLUDED.{0}").format(sql.Identifier(c)) for c in VARIAVEIS.values())
    with conn.cursor() as cur:
        cur.executemany(
            sql.SQL("INSERT INTO {t} (cod_usina, data_hora, {c}, extraido_em) VALUES (%s, %s, {p}, %s) "
                    "ON CONFLICT (cod_usina, data_hora) DO UPDATE SET {u}, extraido_em = EXCLUDED.extraido_em, carregado_em = now()")
            .format(t=tabela(cfg, "tratada", "clima_horario"), c=colunas,
                    p=sql.SQL(", ").join(sql.Placeholder() * len(VARIAVEIS)), u=atualiza),
            linhas,
        )
    conn.commit()
    ex.gravadas += len(linhas)
    nulos = sum(1 for v in VARIAVEIS for x in horario[v] if x is None)
    if nulos:
        ex.avisos.append(f"{nulos} valores nulos devolvidos pela fonte")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Extrai clima horário da Open-Meteo para as usinas.")
    ap.add_argument("--usinas", nargs="+", help="códigos de usina (padrão: todas)")
    ap.add_argument("--refazer", action="store_true", help="baixa todo o período de novo, ignorando o que já está no raw")
    args = ap.parse_args(argv)

    common.configurar_log()
    common.carregar_env()
    cfg = common.carregar_config()
    falhas = 0

    with common.conectar() as conn:
        common.garantir_estrutura(conn, cfg)
        conn.execute(sql.SQL(_DDL_RAW).format(raw=tabela(cfg, "raw", "open_meteo_raw")))
        conn.execute(sql.SQL(_DDL_TRATADA).format(tratada=tabela(cfg, "tratada", "clima_horario")))
        conn.commit()

        sessao = common.nova_sessao(cfg)
        for cod, lat, lon in listar_usinas(cfg, conn, args.usinas):
            try:
                with execucao(cfg, FONTE, cod) as ex:
                    extrair_usina(cfg, conn, sessao, ex, cod, lat, lon, args.refazer)
            except ErroFonte as e:
                conn.rollback()
                falhas += 1
                log.error("%s: %s", cod, e)
    return 1 if falhas else 0


if __name__ == "__main__":
    sys.exit(main())
